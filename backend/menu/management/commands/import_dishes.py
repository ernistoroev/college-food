class Command(BaseCommand):
    help = "Импорт 28 блюд в меню College Food"

    def handle(self, *args, **options):
        category_names = [
            "Горячее", "Супы", "Салаты", "Выпечка", "Напитки"
        ]

        categories = {}
        for order, name in enumerate(category_names, start=1):
            category, _ = Category.objects.get_or_create(
                name=name,
                defaults={"order": order},
            )
            categories[name] = category

        created_count = 0
        updated_count = 0

        for category_name, name, price, weight, portions, description in DISHES:
            _, created = Dish.objects.update_or_create(
                category=categories[category_name],
                name=name,
                defaults={
                    "description": description,
                    "price": Decimal(str(price)),
                    "weight": weight,
                    "weight_unit": "мл" if category_name == "Напитки" else "г",
                    "portions_today": portions,
                    "is_available": True,
                },
            )

            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Готово! Создано: {created_count}, обновлено: {updated_count}."
            )
        )
